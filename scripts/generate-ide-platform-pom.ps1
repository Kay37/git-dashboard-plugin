<#
.SYNOPSIS
    Regenerates ide-platform/pom.xml, the parent POM that puts a local IntelliJ install's jars
    (the platform plus the bundled Git and GitHub plugins) on the plugin's compile classpath.

.DESCRIPTION
    JetBrains only publishes a Gradle build plugin, so this Maven build compiles against the
    IntelliJ installed on this machine instead. Jar names change between IntelliJ versions:
    run this again whenever IntelliJ is updated, then rebuild.

.EXAMPLE
    .\scripts\generate-ide-platform-pom.ps1 -IdeaHome "C:\Program Files\JetBrains\IntelliJ IDEA 2026.3"
#>
param(
    [string]$IdeaHome = "C:\Program Files\JetBrains\IntelliJ IDEA 2026.2.3"
)

$ErrorActionPreference = 'Stop'

$IdeaHome = (Resolve-Path $IdeaHome).Path.TrimEnd('\')
$productInfoPath = Join-Path $IdeaHome 'product-info.json'
if (-not (Test-Path $productInfoPath)) {
    throw "No IntelliJ install found at $IdeaHome (missing product-info.json)."
}
$productInfo = Get-Content $productInfoPath -Raw | ConvertFrom-Json

# lib\ is scanned without subfolders: those hold split-mode and native files that aren't compile dependencies.
$jars = @(
    Get-ChildItem (Join-Path $IdeaHome 'lib') -Filter *.jar -File
    Get-ChildItem (Join-Path $IdeaHome 'plugins\vcs-git\lib') -Filter *.jar -File -Recurse
    Get-ChildItem (Join-Path $IdeaHome 'plugins\vcs-github\lib') -Filter *.jar -File -Recurse
) | Sort-Object FullName

$dependencies = foreach ($jar in $jars) {
    $relative = $jar.FullName.Substring($IdeaHome.Length + 1).Replace('\', '/')
    $artifactId = ($relative -replace '\.jar$', '' -replace '/', '.' -replace '[^A-Za-z0-9_.-]', '_')
@"
        <dependency>
            <groupId>com.jetbrains.intellij.local</groupId>
            <artifactId>$artifactId</artifactId>
            <version>$($productInfo.buildNumber)</version>
            <scope>system</scope>
            <systemPath>`${idea.home}/$relative</systemPath>
        </dependency>
"@
}

$ideaHomeForward = $IdeaHome.Replace('\', '/')
$pom = @"
<?xml version="1.0" encoding="UTF-8"?>
<!--
  GENERATED by scripts/generate-ide-platform-pom.ps1 - do not edit by hand.
  $($productInfo.name) $($productInfo.version) (build $($productInfo.buildNumber)), $($jars.Count) jars.
-->
<project xmlns="http://maven.apache.org/POM/4.0.0"
         xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
         xsi:schemaLocation="http://maven.apache.org/POM/4.0.0 https://maven.apache.org/xsd/maven-4.0.0.xsd">
    <modelVersion>4.0.0</modelVersion>

    <groupId>dev.gitdashboard</groupId>
    <artifactId>ide-platform</artifactId>
    <version>local</version>
    <packaging>pom</packaging>

    <properties>
        <idea.home>$ideaHomeForward</idea.home>
        <idea.build>$($productInfo.buildNumber)</idea.build>
    </properties>

    <dependencies>
$($dependencies -join "`n")
    </dependencies>
</project>
"@

$outDir = Join-Path $PSScriptRoot '..\ide-platform'
New-Item -ItemType Directory -Force $outDir | Out-Null
$outFile = Join-Path (Resolve-Path $outDir) 'pom.xml'
[IO.File]::WriteAllText($outFile, $pom, (New-Object Text.UTF8Encoding $false))
Write-Output "Wrote $outFile ($($jars.Count) jars from $($productInfo.name) $($productInfo.version))"
